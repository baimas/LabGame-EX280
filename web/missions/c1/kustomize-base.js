import { REGISTRY } from '../../engine/world.js';
import { resolveEnv } from '../../sim/controllers.js';

const NS = 'reports-dev';
const DIR = '/home/student/labs/reports/base';

const DEPLOYMENT = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: reports
spec:
  replicas: 2
  selector:
    matchLabels:
      app: reports
  template:
    metadata:
      labels:
        app: reports
    spec:
      containers:
        - name: reports
          image: ${REGISTRY}/nimbus/reports:4.0
          ports:
            - containerPort: 8080
          envFrom:
            - configMapRef:
                name: reports-settings
`;

const SERVICE = `apiVersion: v1
kind: Service
metadata:
  name: reports
spec:
  selector:
    app: reports
  ports:
    - port: 8080
      targetPort: 8080
`;

const KUSTOMIZATION = `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - deployment.yaml
  - service.yaml
commonLabels:
  team: finance
configMapGenerator:
  - name: reports-settings
    literals:
      - REPORT_TZ=America/Sao_Paulo
`;

